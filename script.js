/* =========================
   CRIAR CARD
========================= */

function criarCard(produto){

    let card = document.createElement('div')
    card.className = 'produto'

    if(produto.novidade === true){

        let etiquetaNovo =
            document.createElement('span')

        etiquetaNovo.className =
            'etiqueta-novo'

        etiquetaNovo.textContent =
            'Novo'

        card.appendChild(
            etiquetaNovo
        )
    }   


    let areaImagem = document.createElement('div')
    areaImagem.className = 'area-imagem-produto'

    let imagem = document.createElement('img')
    imagem.src = produto.imagem
    imagem.alt = produto.nome

    areaImagem.appendChild(imagem)


    let nome = document.createElement('h3')
    nome.textContent = produto.nome


    let categoriaP = document.createElement('p')
    categoriaP.className = 'categoria-produto'
    categoriaP.textContent = produto.categoria


    let tamanhos = document.createElement('p')
    tamanhos.className = 'tamanhos-produto'

    if(produto.tamanhos === null){

        tamanhos.textContent =
            'Tamanhos: consultar'

    } else {

        tamanhos.textContent =
            `Tamanhos: ${produto.tamanhos.join(', ')}`
    }


    let preco = document.createElement('p')
    preco.className = 'preco'

    if(produto.preco === null){

        preco.textContent =
            'Consultar preço'

    } else {

        preco.textContent =
            `R$ ${formatarPreco(produto.preco)}`
    }


    let whatsapp = document.createElement('a')

    whatsapp.target = '_blank'
    whatsapp.rel = 'noopener noreferrer'

    whatsapp.className = 'botao-whatsapp'

    whatsapp.textContent =
        'Pedir pelo WhatsApp'


    let mensagem =
        criarMensagem(produto)


    let mensagemCodificada =
        encodeURIComponent(mensagem)


    whatsapp.href =
        `https://wa.me/5511971949711?text=${mensagemCodificada}`


    card.appendChild(areaImagem)

    card.appendChild(nome)

    card.appendChild(categoriaP)

    card.appendChild(tamanhos)

    card.appendChild(preco)

    card.appendChild(whatsapp)


    return card
}


/* =========================
   FORMATAR PREÇO
========================= */

function formatarPreco(preco){

    return preco
        .toFixed(2)
        .replace('.', ',')
}


/* =========================
   MENSAGEM WHATSAPP
========================= */

function criarMensagem(produto){

    let mensagem =
        `Olá! Tenho interesse no ${produto.nome}.`


    if(produto.tamanhos === null){

        mensagem +=
            ` Gostaria de consultar os tamanhos disponíveis.`

    } else {

        mensagem +=
            ` Vi que os tamanhos disponíveis são ${produto.tamanhos.join(', ')}.`
    }


    if(produto.preco === null){

        mensagem +=
            ` Também gostaria de consultar o preço e a disponibilidade.`

    } else {

        mensagem +=
            ` O valor informado é R$ ${formatarPreco(produto.preco)}. Gostaria de consultar a disponibilidade.`
    }


    return mensagem
}


/* =========================
   NORMALIZAR TEXTO
========================= */

function normalizarTexto(texto){

    return texto
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLowerCase()
}


/* =========================
   MOSTRAR PRODUTOS
========================= */

function mostrarProdutos(
    categoria,
    textoBusca,
    somenteNovidades = false
){

    let areaProdutos =
        document.querySelector(
            'div.produtos'
        )


    areaProdutos.innerHTML = ''


    let quantidadeMostrada = 0


    for(let pos in produtos){


        /* -------------------------
           FILTRO DE NOVIDADES
        ------------------------- */

        if(
            somenteNovidades === true &&
            produtos[pos].novidade !== true
        ){
            continue
        }


        /* -------------------------
           FILTRO DE CATEGORIA
        ------------------------- */

        if(
            categoria !== undefined &&
            produtos[pos].categoria !== categoria
        ){
            continue
        }


        /* -------------------------
           FILTRO DE BUSCA
        ------------------------- */

        if(
            textoBusca !== undefined &&
            textoBusca !== ''
        ){

            let palavrasNome =
                normalizarTexto(
                    produtos[pos].nome
                )
                    .split(' ')


            let encontrou = false


            for(let palavra of palavrasNome){

                if(
                    palavra.startsWith(
                        textoBusca
                    )
                ){

                    encontrou = true

                    break
                }
            }


            if(encontrou === false){

                continue
            }
        }


        let card =
            criarCard(
                produtos[pos]
            )


        areaProdutos.appendChild(
            card
        )


        quantidadeMostrada++
    }


    atualizarQuantidade(
        quantidadeMostrada
    )


    if(quantidadeMostrada === 0){

        let mensagem =
            document.createElement('p')


        mensagem.className =
            'mensagem-vazia'


        mensagem.textContent =
            'Nenhum produto encontrado.'


        areaProdutos.appendChild(
            mensagem
        )
    }
}


/* =========================
   CONTADOR
========================= */

function atualizarQuantidade(
    quantidade
){

    let quantidadeProdutos =
        document.querySelector(
            '#quantidade-produtos'
        )


    if(quantidade === 1){

        quantidadeProdutos.textContent =
            '1 produto encontrado'

    } else {

        quantidadeProdutos.textContent =
            `${quantidade} produtos encontrados`
    }
}


/* =========================
   ESTADO ATUAL
========================= */

let categoriaAtual =
    undefined


let textoBuscaAtual =
    ''


let mostrandoNovidades =
    true


/* =========================
   BUSCA
========================= */

let campoBusca =
    document.querySelector(
        '#busca'
    )


campoBusca.addEventListener(
    'input',
    function(){

        textoBuscaAtual =
            normalizarTexto(
                campoBusca.value
            )
                .trim()


        mostrarProdutos(
            categoriaAtual,
            textoBuscaAtual,
            mostrandoNovidades
        )
    }
)


/* =========================
   PRIMEIRA EXIBIÇÃO
========================= */

mostrarProdutos(
    undefined,
    '',
    true
)


/* =========================
   MOSTRAR TODO O CATÁLOGO
========================= */

function mostrarTodos(){

    categoriaAtual =
        undefined


    textoBuscaAtual =
        ''


    mostrandoNovidades =
        false


    campoBusca.value =
        ''


    let categorias =
        document.querySelectorAll(
            '.categoria'
        )


    for(let item of categorias){

        item.classList.remove(
            'ativa'
        )
    }


    mostrarProdutos(
        categoriaAtual,
        textoBuscaAtual,
        mostrandoNovidades
    )


    document
        .querySelector(
            '#novidades'
        )
        .scrollIntoView({
            behavior: 'smooth'
        })
}


/* =========================
   FILTRAR CATEGORIA
========================= */

function clicar(
    categoria,
    elemento
){

    categoriaAtual =
        categoria


    mostrandoNovidades =
        false


    let categorias =
        document.querySelectorAll(
            '.categoria'
        )


    for(let item of categorias){

        item.classList.remove(
            'ativa'
        )
    }


    elemento.classList.add(
        'ativa'
    )


    mostrarProdutos(
        categoriaAtual,
        textoBuscaAtual,
        mostrandoNovidades
    )


    document
        .querySelector(
            '#novidades'
        )
        .scrollIntoView({
            behavior: 'smooth'
        })
}
